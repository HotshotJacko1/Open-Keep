# Runs at container start (the nginx image runs /docker-entrypoint.d/*.sh before
# nginx). Turns the OPENKEEP_* environment variables into:
#   - config.js, which the app reads at startup (src/lib/runtime-config.ts)
#   - an nginx include that forwards /webdav/ to your WebDAV server, when
#     OPENKEEP_WEBDAV_UPSTREAM is set
# See SELF_HOSTING.md for what each variable does.
#
# HTML_DIR and NGINX_INCLUDE are only overridden by tests.

set -eu

HTML_DIR="${HTML_DIR:-/usr/share/nginx/html}"
NGINX_INCLUDE="${NGINX_INCLUDE:-/tmp/open-keep-webdav.conf}"

upstream="${OPENKEEP_WEBDAV_UPSTREAM:-}"
webdav_url="${OPENKEEP_WEBDAV_URL:-}"
webdav_folder="${OPENKEEP_WEBDAV_FOLDER:-}"

fail() {
    echo "open-keep: $*" >&2
    exit 1
}

# A value as a JSON string: escape backslashes and quotes, drop control characters.
json_string() {
    printf '"%s"' "$(printf '%s' "$1" | tr -d '[:cntrl:]' | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"
}

rm -f "$NGINX_INCLUDE"
if [ -n "$upstream" ]; then
    upstream="${upstream%/}"
    # Scheme, host, optional port and a plain path (Nextcloud under /nextcloud):
    # it's written into the nginx config, so nothing else gets through.
    printf '%s' "$upstream" | grep -Eq '^https?://[A-Za-z0-9.-]+(:[0-9]{1,5})?(/[A-Za-z0-9._~%/-]*)?$' \
        || fail "OPENKEEP_WEBDAV_UPSTREAM must look like https://cloud.example.com or https://example.com/nextcloud, got: $upstream"
    cat > "$NGINX_INCLUDE" <<EOF
# Generated by 40-open-keep-config.sh from OPENKEEP_WEBDAV_UPSTREAM.
# /webdav/... on this site is forwarded to $upstream/..., so the browser sees one
# site and the WebDAV server needs no CORS setup.
location /webdav/ {
    proxy_pass $upstream/;
    proxy_ssl_server_name on;
    proxy_http_version 1.1;
    proxy_set_header Connection "";
    # Basic auth only: a session cookie would make Nextcloud demand a CSRF token.
    proxy_set_header Cookie "";
    proxy_hide_header Set-Cookie;
    proxy_request_buffering off;
    client_max_body_size 512m;
    proxy_read_timeout 300s;
}
EOF
    echo "open-keep: forwarding /webdav/ to $upstream"
    # Point the connect form at the forwarded path unless told otherwise.
    [ -n "$webdav_url" ] || webdav_url="/webdav/"
fi

config="{"
sep=""
if [ -n "$webdav_url" ]; then
    config="$config\"webdavUrl\": $(json_string "$webdav_url")"
    sep=", "
fi
if [ -n "$webdav_folder" ]; then
    config="$config$sep\"webdavFolder\": $(json_string "$webdav_folder")"
fi
config="$config}"

printf '// Written by 40-open-keep-config.sh at container start. See SELF_HOSTING.md.\nwindow.__OPEN_KEEP_CONFIG__ = %s;\n' "$config" > "$HTML_DIR/config.js"
echo "open-keep: config.js = $config"
